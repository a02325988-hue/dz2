def get_main_kb(user_id):
    builder = ReplyKeyboardBuilder()
    builder.button(text="🇺🇦 Україна")
    if user_id in user_favorites:
        builder.button(text=f"⭐ Обране: {user_favorites[user_id]}")
    builder.button(text="❓ Допомога")
    builder.adjust(1)
    return builder.as_markup(resize_keyboard=True)
def get_regions_kb():
    builder = ReplyKeyboardBuilder()
    for region in sorted(ECO_DATABASE.keys()):
        builder.button(text=f"🗺 {region}")
    builder.button(text="⬅️ Головна")
    builder.adjust(2)
    return builder.as_markup(resize_keyboard=True)
def get_cities_kb(region_name):
    builder = ReplyKeyboardBuilder()
    for city in ECO_DATABASE.get(region_name, {}).keys():
        builder.button(text=city)
    builder.button(text="⬅️ До областей")
    builder.adjust(1)
    return builder.as_markup(resize_keyboard=True)
def get_city_actions_kb(city):
    builder = ReplyKeyboardBuilder()
    builder.button(text=f"🔎 Еко-аналіз {city}")
    builder.button(text=f"♻️ Де здати сміття у {city}")
    builder.button(text=f"⭐ Додати {city} в обране")
    builder.button(text="⬅️ До областей")
    builder.adjust(1)
    return builder.as_markup(resize_keyboard=True)
@dp.message(Command("start"))
async def cmd_start(message: types.Message):
    await message.answer(
        "👋 Вітаємо в системі професійного екологічного моніторингу!\n\n"
        "Оберіть регіон, щоб отримати **максимально детальну** інформацію про стан повітря, води, ґрунту "
        "та дізнатися, як саме ви можете вплинути на ситуацію.",
        reply_markup=get_main_kb(message.from_user.id)
    )
@dp.message(F.text == "🇺🇦 Україна")
async def select_country(message: types.Message):
    await message.answer("Оберіть область для детального вивчення:", reply_markup=get_regions_kb())
@dp.message(F.text.startswith("🗺 "))
async def select_region(message: types.Message):
    region_name = message.text.replace("🗺 ", "")
    await message.answer(f"Аналізуємо {region_name} область. Оберіть місто:", reply_markup=get_cities_kb(region_name))

@dp.message(F.text.startswith("📍 "))
async def select_city(message: types.Message):
    city_name = message.text
    await message.answer(f"🌍 Ви обрали {city_name}.\nОберіть категорію інформації:", reply_markup=get_city_actions_kb(city_name))
